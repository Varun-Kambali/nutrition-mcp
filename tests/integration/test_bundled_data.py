import csv
from pathlib import Path

from nutrition_mcp.loader import build_registry, bundled_dir, load_dataset

MAP_PATH = Path(__file__).parents[2] / "data_build" / "ingredient_map.csv"
SOURCE_IDS = {"usda": "usda_fdc", "cofid": "cofid_2021"}


def test_bundled_ingredients_load() -> None:
    _, ingredients, _ = load_dataset(bundled_dir())
    assert len(ingredients) >= 50
    lacking = [i.id for i in ingredients if i.per_100g.kcal is None or i.per_100g.protein_g is None]
    assert lacking == []


def test_bundled_registry_builds_with_every_source() -> None:
    # Building the registry checks that every source_id names an entry in sources.yaml.
    registry = build_registry([])
    assert {s.id for s in registry.sources()} == {
        "usda_fdc",
        "cofid_2021",
        "recipes_cc_by",
        "gi_compendium_2021",
    }


def test_bundled_ingredients_match_the_map() -> None:
    # ingredients.csv is generated by scripts/build_ingredients.py from the map. This catches
    # a map change without a rebuild, or a hand edit to the identity columns of the CSV.
    # Nutrient values need the source records, which CI does not have; `make data` followed
    # by `git diff` checks those.
    with MAP_PATH.open(encoding="utf-8", newline="") as handle:
        expected = [
            (
                row["id"],
                row["name"],
                [alias for alias in row["aliases"].split("|") if alias],
                row["diet"],
                SOURCE_IDS[row["source"]],
                row["record"],
            )
            for row in csv.DictReader(handle)
        ]
    _, ingredients, _ = load_dataset(bundled_dir())
    actual = [(i.id, i.name, i.aliases, i.diet, i.source_id, i.source_record) for i in ingredients]
    assert actual == expected
